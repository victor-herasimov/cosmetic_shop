"""
Модуль для роботи з елементами замовлень.

Забезпечує бізнес-логіку створення, підрахунку вартості та керування
окремими товарними позиціями (OrderItem) у кошиках та замовленнях користувачів.
"""

from order.models import OrderItem


class OrderItemService:
    """
    Сервіс для керування життєвим циклом елементів замовлення (OrderItem).

    Включає логіку створення, оновлення та обробки окремих товарних
    позицій, що входять до складу замовлень.
    """

    @classmethod
    def create(cls, **kwargs) -> OrderItem:
        """Створює та зберігає новий елемент замовлення в базі даних."""
        return OrderItem.objects.create(**kwargs)
