"""Кастомні Django template filters для форматування даних замовлень.

Цей модуль містить фільтр для коректного відображення граматичних
форм слів залежно від числових значень (плюралізація).
"""

from django import template

register = template.Library()


@register.filter
def order_pluralize(n: int) -> str:
    """Повертає правильну форму слова «замовлення» залежно від кількості.

    Враховує особливості плюралізації в українській мові:
    - 1, 21, 31... -> "замовлення"
    - 2, 3, 4, 22, 23, 24... -> "замовлення"
    - 0, 5-20, 25-30, 11-19... -> "замовлень"

    Args:
        n (int): Кількість замовлень.

    Returns:
        str: Відмінена форма слова ("замовлення" або "замовлень").

    Example:
        У Django-шаблоні:
        ```html
        {{ count }} {{ count|order_pluralize }}
        <!-- 1 замовлення, 3 замовлення, 5 замовлень -->
        ```
    """

    mod_10: int = n % 10
    mod_100: int = n % 100

    if mod_10 == 1 and mod_100 != 11:
        return "замовлення"
    if 2 <= mod_10 <= 4 and not (11 <= mod_100 <= 19):
        return "замовлення"
    return "замовлень"
