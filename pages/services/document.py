"""
Сервісний шар для роботи з інформаційними та юридичними документами.

Містить класи-сервіси, які інкапсулюють бізнес-логіку взаємодії з моделями даних,
зокрема спрощують отримання синглтон-об'єктів сайту.
"""

from solo.models import SingletonModel


class DocumentService:
    """
    Сервіс для керування та отримання екземплярів синглтон-моделей документів.
    """

    def __init__(self, model: SingletonModel) -> None:
        """
        Ініціалізує сервіс конкретною синглтон-моделлю.

        Args:
            model (SingletonModel): Клас моделі Django (наприклад, `PrivacyPolicy`),
                який наслідує `SingletonModel` і з яким працюватиме цей сервіс.
        """
        self.model = model

    def get(self) -> SingletonModel:
        """
        Повертає єдиний існуючий екземпляр моделі (або створює дефолтний, якщо його немає).
        """
        return self.model.get_solo()
