"""
Модель Політики повернення сайту.
"""

from .base_legal_document import BaseLegalDocument


class ReturnPolicy(BaseLegalDocument):
    """
    Модель для керування Політикою повернення сайту.

    Успадковує поведінку синглтона та структуру текстових полів від `BaseLegalDocument`.
    Дозволяє адміністратору редагувати офіційний текст угоди про повернення
    в одному екземплярі через адмін-панель.
    """

    class Meta:
        """Мета-параметри для відображення моделі в адмін-панелі Django."""

        verbose_name = "Повернення та обмін"
        verbose_name_plural = "Повернення та обмін"

    def __str__(self) -> str:
        """Повертає текстове представлення — заголовок документа Політики."""
        return self.title
