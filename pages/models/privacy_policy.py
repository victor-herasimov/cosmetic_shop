"""
Модель Політики конфіденційності сайту.
"""

from .base_legal_document import BaseLegalDocument


class PrivacyPolicy(BaseLegalDocument):
    """
    Модель для керування Політикою конфіденційності сайту.

    Успадковує поведінку синглтона та структуру текстових полів від `BaseLegalDocument`.
    Дозволяє адміністратору редагувати офіційний текст угоди про обробку персональних
    даних в одному екземплярі через адмін-панель.
    """

    class Meta:
        """Мета-параметри для відображення моделі в адмін-панелі Django."""

        app_label = "pages"
        verbose_name = "Політика конфіденційності"
        verbose_name_plural = "Політика конфіденційності"

    def __str__(self) -> str:
        """Повертає текстове представлення — заголовок документа Політики."""
        return self.title
