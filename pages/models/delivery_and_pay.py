"""
Модель Політики оплати та доставки.
"""

from .base_legal_document import BaseLegalDocument


class DeliveryAndPayPolicy(BaseLegalDocument):
    """
    Модель для керування Політикою оплата та доставок сайту.

    Успадковує поведінку синглтона та структуру текстових полів від `BaseLegalDocument`.
    Дозволяє адміністратору редагувати офіційний текст угоди про оплату та доставку
    в одному екземплярі через адмін-панель.
    """

    class Meta:
        """Мета-параметри для відображення моделі в адмін-панелі Django."""

        app_label = "pages"
        verbose_name = "Оплата та доствака"
        verbose_name_plural = "Оплата та доствака"

    def __str__(self) -> str:
        """Повертає текстове представлення — заголовок документа Політики."""
        return self.title
