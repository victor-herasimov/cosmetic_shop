"""
Модуль допоміжних класів (міксинів) для моделей додатка.

Містить абстрактні класи, які реалізують повторювану логіку або стандартні поля
(наприклад, часові мітки), для їх зручного повторного використання в інших моделях.
"""

from django.db import models


class DateMixin(models.Model):
    """
    Абстрактна модель-міксин для автоматичного відстеження часу створення та оновлення записів.

    Додає до моделі-спадкоємця два поля: дату створення (`created`) та дату останньої
    модифікації (`updated`). Не створює окремої таблиці в базі даних.
    """

    created = models.DateTimeField(auto_now_add=True, verbose_name="Дата створення")
    updated = models.DateTimeField(auto_now=True, verbose_name="Дата оновлення")

    class Meta:
        """Мета-параметри, що визначають клас як абстрактний міксин."""

        abstract = True
